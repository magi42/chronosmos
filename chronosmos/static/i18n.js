export function detectLanguage(languages) {
  return (
    languages
      .map((l) => l.toLowerCase().split("-")[0])
      .find((l) => l === "en" || l === "fi") || "en"
  );
}
export let language =
  localStorage.getItem("chronosmos-language") ||
  detectLanguage(navigator.languages || [navigator.language]);
if (!translations[language]) language = "en";
export const t = (key, locale = language) =>
  translations[locale]?.[key] ?? translations.en[key] ?? key;
export function translate() {
  document.documentElement.lang = language;
  document
    .querySelectorAll("[data-i18n]")
    .forEach((e) => (e.textContent = t(e.dataset.i18n)));
  document
    .querySelectorAll(".language")
    .forEach((e) => (e.textContent = language === "en" ? "FI" : "EN"));
}
export function toggleLanguage() {
  language = language === "en" ? "fi" : "en";
  localStorage.setItem("chronosmos-language", language);
  translate();
  window.dispatchEvent(new Event("languagechange"));
}
